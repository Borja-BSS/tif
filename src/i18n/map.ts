// ── Registre des langues — ajouter ici au fur et à mesure ────────────────────
const TRANSLATIONS: Record<string, MapT> = {
  fr: FR,
  en: EN,
  de: DE,
  it: IT,
  es: ES,
  pt: PT,
  sq: SQ,
  ja: JA,
  zh: ZH,
}

// ── Hook React — lit tif-lang dans localStorage ───────────────────────────────
export function useMapT(): MapT {
  const [t, setT] = useState<MapT>(FR)

  useEffect(() => {
    const read = (): MapT => {
      try {
        const lang = localStorage.getItem('tif-lang') ?? 'fr'
        return TRANSLATIONS[lang] ?? FR
      } catch {
        return FR
      }
    }
    setT(read())
    const handler = (e: StorageEvent) => {
      if (e.key === 'tif-lang') setT(read())
    }
    window.addEventListener('storage', handler)
    return () => window.removeEventListener('storage', handler)
  }, [])

  return t
}
